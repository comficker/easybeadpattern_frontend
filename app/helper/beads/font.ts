export const GLYPHS = G
export const FONT_HEIGHT = 7
export const SUPPORTED = Object.keys(G).join('')

// "<3" is typed more often than the heart symbol.
export function normalise(text: string): string {
    return text.toUpperCase().replace(/<3/g, '♥').split('').filter(ch => ch in G || ch === '\n').join('')
}

export interface LetterOptions {
    text: string
    letter: RGB
    // null: no background, letters only.
    background: RGB | null
    // Beads between letters and around the whole word.
    spacing: number
    padding: number
}

// Renders text (one line per \n) into a SourceGrid.
export function textToSource(o: LetterOptions): SourceGrid | null {
    const lines = normalise(o.text).split('\n').map(l => l.trim()).filter(Boolean)
    if (!lines.length) return null
    const lineWidth = (l: string) => [...l].reduce((w, ch, i) => w + G[ch]![0]!.length + (i ? o.spacing : 0), 0)
    const inner = Math.max(...lines.map(lineWidth))
    const lineGap = 2
    const width = inner + 2 * o.padding
    const height = lines.length * FONT_HEIGHT + (lines.length - 1) * lineGap + 2 * o.padding
    const cells: (RGB | null)[] = new Array(width * height).fill(o.background)
    lines.forEach((line, li) => {
        // Each line is centred.
        let x = o.padding + Math.floor((inner - lineWidth(line)) / 2)
        const y0 = o.padding + li * (FONT_HEIGHT + lineGap)
        ;[...line].forEach((ch, i) => {
            if (i) x += o.spacing
            const g = G[ch]!
            for (let gy = 0; gy < FONT_HEIGHT; gy++) for (let gx = 0; gx < g[0]!.length; gx++) {
                if (g[gy]![gx] === '#') cells[(y0 + gy) * width + x + gx] = o.letter
            }
            x += g[0]!.length
        })
    })
    return {width, height, cells}
}
